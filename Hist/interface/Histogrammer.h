// Config-driven histogramming of HELL analysis trees.
//
// Input: flat trees written by TreeWriter (any TTree works). Cuts, weights
// and variables are TTree expressions (TTreeFormula), so no recompilation
// is needed to change a selection. Each MC sample is normalised to
// lumi * xsec / sumw, where sumw is the sum of generator weights of ALL
// generated events (hell/counts "genEventSumw", summed over the files).
//
// Output: <region>/<variable>/<process> and
//         <region>/<variable>/<process>_<systematic>(Up|Down)
// Two kinds of systematics:
//   weight: alternative weight expression (e.g. "Weight_puUp/Weight_nominal")
//   tree:   alternative input files (one job per object-level variation)
//
// JSON configuration (generated by `hell hist` from the python/yaml config):
// {
//  "output": "hists.root", "treeName": "Events", "lumi": 7980.0,
//  "processes": [{"name": "tch", "label": "t-channel", "color": "#e42536", "isData": false, "cut": "",
//                 "samples": [{"name": "TbarBQ", "files": [...], "xsec": 87.2, "sumw": 0,
//                              "variations": {"jesUp": [...files...]}}]}],
//  "regions": {"2j1b_mu": {"selection": "st_nJet==2 && st_nBJet==1 && st_isMuon", "weight": "Weight_nominal"}},
//  "variables": {"topMass": {"expr": "st_topMass", "bins": [20,100,300], "title": "m_{l#nub} [GeV]"}},
//  "systematics": {"pu": {"type": "weight", "up": "Weight_puUp/Weight_nominal", "down": "..."},
//                  "jes": {"type": "tree", "up": "jesUp", "down": "jesDown"}}
// }
#pragma once
#include <TH1D.h>
#include <nlohmann/json.hpp>
#include <map>
#include <memory>
#include <string>
#include <vector>

namespace hell {

struct HistVariable {
  std::string name, expr, title;
  std::vector<double> edges;
};
struct HistRegion {
  std::string name, selection, weight;
};
struct HistSystematic {
  std::string name, type, up, down;  // type: weight | tree
};
struct HistSample {
  std::string name;
  std::vector<std::string> files;
  double xsec = 0, sumw = 0;
  std::map<std::string, std::vector<std::string>> variationFiles;
};
struct HistProcess {
  std::string name, label, color, cut;
  bool isData = false;
  std::vector<HistSample> samples;
};

class Histogrammer {
 public:
  explicit Histogrammer(const nlohmann::json& config);
  int run();
  // sum of genEventSumw over the files (from hell/counts)
  static double readSumw(const std::vector<std::string>& files, const std::string& label = "genEventSumw");

 private:
  void parse(const nlohmann::json& cfg);
  TH1D* hist(const std::string& region, const std::string& var, const std::string& process, const std::string& syst);
  void processFiles(const HistProcess& p, const HistSample& s, const std::vector<std::string>& files, const std::string& systName,
                    double scale, bool weightSystematics);

  nlohmann::json config_;
  std::string output_, treeName_;
  double lumi_ = 1;
  std::vector<HistVariable> variables_;
  std::vector<HistRegion> regions_;
  std::vector<HistSystematic> systematics_;
  std::vector<HistProcess> processes_;
  std::map<std::string, std::unique_ptr<TH1D>> hists_;
  long long maxEvents_ = -1;
};

}  // namespace hell
