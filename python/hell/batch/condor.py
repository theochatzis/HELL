"""Flexible HTCondor submission of HELL jobs.

A "task" is a directory ~/hell_condor/<tag>/ with:
  jobs.json    job id -> {command, args, output}   (what each job runs)
  jobs.txt     the queue (one id per line)
  job.sh       wrapper: unpack HELL, source env, run the command, copy outputs
  job.sub      condor submit file
  hell.tar.gz  the framework (build/bin, build/lib, python, configs, samples, env)
  meta.json    how the task was created (for `hell check`, `hell resubmit`, `hell merge`)

Kinds of job:
  run    hell run <cfg.py> with a chunk of files of a sample (--files-per-job / --events-per-job)
  hist   hell hist <hist.yaml> for one process (or all)
  train  hell train <ml.yaml> (one job, optionally GPU)
  cmd    an arbitrary hell command line per job (from a text file)

`hell submit run configs/SingleTopMass/skim_cfg.py --sample TbarBQtoLNu_tch TTtoLNu2Q --era 2022 \
     --files-per-job 10 --output-dir /eos/user/x/HELL/skims/2022 --tag skim_v1`
`hell check --tag skim_v1`  `hell resubmit --tag skim_v1`  `hell merge --tag skim_v1`
"""
import json
import os
import shutil
import subprocess
import tarfile

from hell import HELL_BASE, HELL_BUILD, HellError, log, warn
from hell import samples as S

JOB_SH = r"""#!/bin/bash
# HELL condor job wrapper (generated by `hell submit`).
set -e
JOBID="$1"
echo "[HELL] job $JOBID starting on $(hostname) at $(date)"
TASKDIR="{taskdir}"
mkdir -p hell_job && cd hell_job
tar xzf "$TASKDIR/hell.tar.gz"
export HELL_ENV={hell_env}
source HELL/env/setup.sh
{proxy_line}
python3 - "$JOBID" <<'PYEOF'
import json, os, subprocess, sys, shlex
jobid = sys.argv[1]
jobs = json.load(open(os.path.join("{taskdir}", "jobs.json")))
job = jobs[jobid]
cmd = job["command"]
print("[HELL] running:", cmd, flush=True)
rc = subprocess.call(cmd, shell=True)
if rc != 0:
    print("[HELL] ERROR: command failed with code", rc, flush=True)
    sys.exit(rc)
for local, dest in job.get("outputs", {{}}).items():
    if not os.path.exists(local):
        print("[HELL] ERROR: expected output", local, "missing", flush=True); sys.exit(2)
    if dest.startswith("root://"):
        subprocess.check_call(["xrdcp", "-f", local, dest])
    else:
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        subprocess.check_call(["cp", "-f", local, dest])
    print("[HELL] copied", local, "->", dest, flush=True)
print("[HELL] job done.", flush=True)
PYEOF
"""

JOB_SUB = """# HELL condor submit file (generated by `hell submit`)
universe   = vanilla
executable = {taskdir}/job.sh
arguments  = $(jobid)
output     = {taskdir}/logs/$(jobid).out
error      = {taskdir}/logs/$(jobid).err
log        = {taskdir}/logs/condor.log
+JobFlavour = "{flavour}"
request_cpus = {cpus}
request_memory = {memory}
{extra}
getenv = False
should_transfer_files = NO
max_retries = {retries}
requirements = Machine =!= LastRemoteHost
queue jobid from {taskdir}/jobs.txt
"""


def work_root():
    home = os.path.expanduser("~")
    # condor schedds reject submit files on EOS: fall back to AFS/local
    if home.startswith("/eos"):
        root = os.path.join("/tmp", os.environ.get("USER", "hell"), "hell_condor")
    else:
        root = os.path.join(home, "hell_condor")
    return os.environ.get("HELL_CONDOR_WORK", root)


def eos_to_xrootd(path):
    if path.startswith("/eos/user/") or path.startswith("/eos/home-"):
        return "root://eosuser.cern.ch/" + path
    if path.startswith("/eos/cms/"):
        return "root://eoscms.cern.ch/" + path
    return path


def pack(taskdir):
    """Pack the framework into the task directory (so workers need only cvmfs)."""
    tgz = os.path.join(taskdir, "hell.tar.gz")
    with tarfile.open(tgz, "w:gz") as tar:
        for rel in ("build/bin", "build/lib", "python", "configs", "samples", "env", "bin", "analyses"):
            src = os.path.join(HELL_BASE, rel)
            if os.path.exists(src):
                tar.add(src, arcname=os.path.join("HELL", rel), filter=lambda ti: None if ti.name.endswith((".pyc", ".o")) or "__pycache__" in ti.name or "/CMakeFiles" in ti.name else ti)
    log(f"packed framework into {tgz} ({os.path.getsize(tgz) / 1e6:.1f} MB)")
    return tgz


def chunks(items, n):
    for i in range(0, len(items), n):
        yield items[i:i + n]


def make_task(tag, jobs, meta, flavour="workday", cpus=1, memory="2000MB", retries=2, extra_sub="", proxy=False, hell_env=None):
    taskdir = os.path.join(work_root(), tag)
    if os.path.exists(os.path.join(taskdir, "jobs.json")):
        raise HellError(f"task {tag} exists at {taskdir}: choose another --tag or remove it")
    os.makedirs(os.path.join(taskdir, "logs"), exist_ok=True)
    with open(os.path.join(taskdir, "jobs.json"), "w") as f:
        json.dump(jobs, f, indent=1)
    with open(os.path.join(taskdir, "jobs.txt"), "w") as f:
        f.write("\n".join(jobs.keys()) + "\n")
    proxy_line = ""
    if proxy:
        src = os.environ.get("X509_USER_PROXY", f"/tmp/x509up_u{os.getuid()}")
        if os.path.exists(src):
            shutil.copy(src, os.path.join(taskdir, "x509_proxy"))
            proxy_line = f"export X509_USER_PROXY={taskdir}/x509_proxy"
        else:
            warn("no VOMS proxy found (voms-proxy-init --voms cms); remote files will not be readable")
    with open(os.path.join(taskdir, "job.sh"), "w") as f:
        f.write(JOB_SH.format(taskdir=taskdir, proxy_line=proxy_line, hell_env=hell_env or os.environ.get("HELL_ENV", "lcg")))
    os.chmod(os.path.join(taskdir, "job.sh"), 0o755)
    with open(os.path.join(taskdir, "job.sub"), "w") as f:
        f.write(JOB_SUB.format(taskdir=taskdir, flavour=flavour, cpus=cpus, memory=memory, retries=retries, extra=extra_sub))
    meta = dict(meta, tag=tag, taskdir=taskdir, n_jobs=len(jobs))
    with open(os.path.join(taskdir, "meta.json"), "w") as f:
        json.dump(meta, f, indent=1)
    pack(taskdir)
    log(f"task {tag}: {len(jobs)} jobs prepared in {taskdir}")
    return taskdir


def submit(taskdir, dry_run=False):
    sub = os.path.join(taskdir, "job.sub")
    if dry_run:
        log(f"dry run: condor_submit {sub}")
        return 0
    env = {k: v for k, v in os.environ.items() if not v.startswith("/eos")}  # schedd rejects EOS paths in env
    log(f"condor_submit {sub}")
    return subprocess.call(["condor_submit", sub], env=env)


def jobs_for_run(cfg, samples, era, output_dir, files_per_job=10, events_per_job=0, max_files=-1, options=(), variation="nominal"):
    """One hell-run job per chunk of files of each sample."""
    jobs = {}
    stem = os.path.splitext(os.path.basename(cfg))[0]
    for sname in samples:
        sample = S.find_sample(sname, era)
        files = S.files(sample, max_files)
        if not files:
            raise HellError(f"sample {sname} has no files (run `hell samples files --era {era} {sname}`)")
        for i, chunk in enumerate(chunks(files, files_per_job)):
            jid = f"{sname}_{stem}_{i:04d}" + ("" if variation == "nominal" else f"_{variation}")
            out = f"{jid}.root"
            dest = os.path.join(output_dir + ("" if variation == "nominal" else f"_{variation}"), sname, out)
            cmd = (f"hell run HELL/{os.path.relpath(os.path.realpath(cfg), HELL_BASE)} sample={sname} era={era} "
                   f"inputFiles={','.join(chunk)} outputFile={out} variation={variation} " + " ".join(options))
            jobs[jid] = {"command": cmd, "sample": sname, "files": chunk, "outputs": {out: eos_to_xrootd(dest)}, "final": dest}
    return jobs


def jobs_for_hist(hist_yaml, processes, output_dir, options=()):
    jobs = {}
    stem = os.path.splitext(os.path.basename(hist_yaml))[0]
    for p in processes:
        out = f"{stem}_{p}.root"
        dest = os.path.join(output_dir, out)
        cmd = f"hell hist HELL/{os.path.relpath(os.path.realpath(hist_yaml), HELL_BASE)} --process {p} -o {out} " + " ".join(options)
        jobs[f"hist_{p}"] = {"command": cmd, "outputs": {out: eos_to_xrootd(dest)}, "final": dest}
    return jobs


def jobs_for_train(ml_yaml, output_dir, options=()):
    stem = os.path.splitext(os.path.basename(ml_yaml))[0]
    out = f"{stem}_model.json"
    dest = os.path.join(output_dir, out)
    cmd = f"hell train HELL/{os.path.relpath(os.path.realpath(ml_yaml), HELL_BASE)} --output-dir . " + " ".join(options)
    return {f"train_{stem}": {"command": cmd, "outputs": {out: eos_to_xrootd(dest)}, "final": dest}}


def jobs_from_commands(path, output_dir):
    """One job per line of a text file: 'id | command | local_output'."""
    jobs = {}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = [p.strip() for p in line.split("|")]
            if len(parts) < 2:
                raise HellError(f"bad command line '{line}': expected 'id | command [| output]'")
            jid, cmd = parts[0], parts[1]
            outputs = {}
            if len(parts) > 2 and parts[2]:
                outputs[parts[2]] = eos_to_xrootd(os.path.join(output_dir, parts[2]))
            jobs[jid] = {"command": cmd, "outputs": outputs, "final": os.path.join(output_dir, parts[2]) if outputs else ""}
    return jobs


def check(tag):
    """Verify the outputs of a task; writes resubmit.txt with the failed ids."""
    import ROOT
    ROOT.gErrorIgnoreLevel = ROOT.kError
    taskdir = os.path.join(work_root(), tag)
    jobs = json.load(open(os.path.join(taskdir, "jobs.json")))
    bad = []
    for jid, job in jobs.items():
        ok = True
        final = job.get("final")
        if final and final.endswith(".root"):
            f = ROOT.TFile.Open(final) if os.path.exists(final) else None
            if not f or f.IsZombie() or f.TestBit(ROOT.TFile.kRecovered) or not f.Get("hell/counts"):
                ok = False
            if f:
                f.Close()
        elif final:
            ok = os.path.exists(final)
        if not ok:
            bad.append(jid)
    with open(os.path.join(taskdir, "resubmit.txt"), "w") as f:
        f.write("\n".join(bad) + ("\n" if bad else ""))
    log(f"task {tag}: {len(jobs) - len(bad)}/{len(jobs)} jobs have good output" + (f"; {len(bad)} to resubmit (hell resubmit --tag {tag})" if bad else ". All forged."))
    return bad


def resubmit(tag, dry_run=False):
    taskdir = os.path.join(work_root(), tag)
    bad = check(tag)
    if not bad:
        return 0
    with open(os.path.join(taskdir, "jobs.txt"), "w") as f:
        f.write("\n".join(bad) + "\n")
    return submit(taskdir, dry_run)


def merge_task(tag, force=False):
    from hell.merge import merge
    taskdir = os.path.join(work_root(), tag)
    jobs = json.load(open(os.path.join(taskdir, "jobs.json")))
    meta = json.load(open(os.path.join(taskdir, "meta.json")))
    by_sample = {}
    for jid, job in jobs.items():
        if job.get("sample") and job.get("final"):
            by_sample.setdefault(job["sample"], []).append(job["final"])
    if not by_sample:
        raise HellError("nothing to merge in this task (only run tasks are merged per sample)")
    outdir = os.path.join(meta.get("output_dir", taskdir), "merged")
    outs = []
    for s, files in by_sample.items():
        outs.append(merge([f for f in files if os.path.exists(f)], os.path.join(outdir, f"{s}.root"), force=force))
    return outs


def status(tag):
    taskdir = os.path.join(work_root(), tag)
    if not os.path.exists(taskdir):
        raise HellError(f"no task {tag} under {work_root()}")
    try:
        out = subprocess.run(["condor_q", "-nobatch", "-constraint", f'regexp("{taskdir}", Cmd)'], capture_output=True, text=True).stdout
    except FileNotFoundError:
        out = "(condor_q not available)"
    print(out)
    return check(tag)
